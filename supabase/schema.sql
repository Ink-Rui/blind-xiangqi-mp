-- ---------------------------------------------------------------------------
-- 每日一局排行榜
-- day 用 YYYY-MM-DD 文本；同一设备同一天只保留一行，客户端只提交更好的成绩。
-- score：胜 3 / 和 1 / 负 0；rank_score 由前端算好，服务端只按它倒序
-- （胜：手数少、用时短更高；和/负：撑得越久越高）。
-- ---------------------------------------------------------------------------
create table if not exists public.daily_scores (
  id         bigint generated by default as identity primary key,
  day        text not null,
  client_id  text not null,
  name       text not null,
  score      smallint not null default 0,
  result     text not null,
  moves      integer not null default 0,
  ms         integer not null default 0,
  rank_score bigint not null default 0,
  created_at timestamptz not null default now(),
  unique (day, client_id)
);

alter table public.daily_scores enable row level security;

-- 匿名前端只能读榜、提交自己的成绩、覆盖自己当天的成绩。
-- client_id 由浏览器本地生成，属于「防作弊不严格」的休闲榜。
drop policy if exists daily_scores_select on public.daily_scores;
create policy daily_scores_select on public.daily_scores for select to anon using (true);

drop policy if exists daily_scores_insert on public.daily_scores;
create policy daily_scores_insert on public.daily_scores for insert to anon with check (true);

drop policy if exists daily_scores_update on public.daily_scores;
create policy daily_scores_update on public.daily_scores for update to anon using (true) with check (true);

grant select, insert, update on public.daily_scores to anon;

create index if not exists daily_scores_rank_idx
  on public.daily_scores (day, rank_score desc, created_at asc);

